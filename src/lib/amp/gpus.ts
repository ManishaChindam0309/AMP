export function getGpu(id: string): GpuSpec {
  return GPUS.find((g) => g.id === id) ?? GPUS[0];
}

export function matchGpu(text: string): string | null {
  const hay = text.toLowerCase();
  for (const gpu of GPUS) {
    if (gpu.aliases.some((alias) => hay.includes(alias))) return gpu.id;
  }
  return null;
}
